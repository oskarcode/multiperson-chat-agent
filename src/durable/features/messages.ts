// Message and transcript behavior. This module only stores/retrieves committed
// chat records; model prompting lives in src/agent/reply.ts and route code.
import type { DurableFeatureContext, StorageFeatureContext } from "../feature-context";
import type { ChatMessage } from "../../protocol/chat";
import { messageFromRow, type MessageRow } from "../rows";
import { MAX_MESSAGE_LENGTH, now, safeText } from "../validation";

export async function listMessages(ctx: DurableFeatureContext, input: { actorId: string; workspaceId: string }): Promise<ChatMessage[]> {
  await ctx.requireWorkspaceMember(input.actorId, input.workspaceId);
  return ctx.state.storage.sql
    .exec<MessageRow>(
      "SELECT id, workspace_id, author_id, author_name, kind, text, created_at FROM messages WHERE workspace_id = ? ORDER BY id ASC LIMIT 300",
      input.workspaceId,
    )
    .toArray()
    .map(messageFromRow);
}

export async function recentTranscript(ctx: DurableFeatureContext, input: { actorId: string; workspaceId: string; limit: number }): Promise<ChatMessage[]> {
  await ctx.requireWorkspaceMember(input.actorId, input.workspaceId);
  return recentWorkspaceMessages(ctx, input.workspaceId, input.limit);
}

// Group and Ask Agent request messages both originate from a member, so both
// pass through room authorization before insertion.
export async function appendGroupMessage(ctx: DurableFeatureContext, input: { actorId: string; workspaceId: string; text: string; kind: "group" | "agent-request" }): Promise<ChatMessage> {
  const actor = await ctx.requireWorkspaceMember(input.actorId, input.workspaceId);
  const message = insertMessage(ctx, input.workspaceId, actor.id, actor.name, input.kind, safeText(input.text, "Message", MAX_MESSAGE_LENGTH));
  await ctx.trackFollowUp(message);
  return message;
}

// Agent messages are generated by trusted server-side flows after the triggering
// user request has already passed authorization.
export async function appendAgentMessage(ctx: DurableFeatureContext, input: { workspaceId: string; text: string }): Promise<ChatMessage> {
  const message = insertMessage(ctx, input.workspaceId, "agent", "Group Agent", "agent", safeText(input.text, "Agent message", MAX_MESSAGE_LENGTH));
  await ctx.trackFollowUp(message);
  return message;
}

export function recentWorkspaceMessages(ctx: StorageFeatureContext, workspaceId: string, limit: number): ChatMessage[] {
  return ctx.state.storage.sql
    .exec<MessageRow>(
      "SELECT id, workspace_id, author_id, author_name, kind, text, created_at FROM messages WHERE workspace_id = ? ORDER BY id DESC LIMIT ?",
      workspaceId,
      Math.max(1, Math.min(limit, 40)),
    )
    .toArray()
    .reverse()
    .map(messageFromRow);
}

export function insertMessage(ctx: StorageFeatureContext, workspaceId: string, authorId: string, authorName: string, kind: ChatMessage["kind"], text: string): ChatMessage {
  const createdAt = now();
  const id = ctx.state.storage.sql
    .exec<{ id: number }>(
      "INSERT INTO messages (workspace_id, author_id, author_name, kind, text, created_at) VALUES (?, ?, ?, ?, ?, ?) RETURNING id",
      workspaceId,
      authorId,
      authorName,
      kind,
      text,
      createdAt,
    )
    .one().id;
  return { id, workspaceId, authorId, authorName, kind, text, createdAt };
}
